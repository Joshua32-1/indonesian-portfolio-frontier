#!/usr/bin/env node
/**
 * refresh-bi-rate.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Node.js ESM script (run via: npm run refresh-bi-rate).
 *
 * Scrapes Bank Indonesia's full policy-rate decision table and folds it into the
 * committed cache data/bi-rate.json — the fallback every app resolves r_f from.
 * Driven by the weekday cron .github/workflows/refresh-bi-rate.yml so a rate move
 * is picked up the day it happens rather than at the next Sunday rebalance.
 *
 * WRITES ONLY ON A REAL CHANGE. The `generated` timestamp alone must never dirty
 * the file, or a weekday cron would land ~250 no-op commits a year instead of the
 * ~8 that match BI's actual meeting calendar. When nothing moved the file is left
 * byte-identical and `git diff --quiet` naturally skips the commit.
 *
 * History is UNIONED, never replaced: if BI ever trims its rendered table we keep
 * the decisions already captured. Downstream, rateAsOf() only ever needs the rows
 * at-or-before a query date, so a longer cache is strictly better.
 *
 * Exit code is 0 whether or not anything changed — "no change" is the common case,
 * not an error. The workflow reads the `changed` output instead.
 * ─────────────────────────────────────────────────────────────────────────────
 */
import { readFileSync, writeFileSync, existsSync, appendFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { fetchBIRateSeries, BI_RATE_URL } from './bi-rate.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CACHE = join(__dirname, 'bi-rate.json');

/** Emit a step output when running under GitHub Actions; no-op locally. */
function setOutput(key, value) {
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `${key}=${value}\n`);
}

function finish(changed, summary) {
  console.log(`\n${summary}`);
  setOutput('changed', changed ? 'true' : 'false');
  process.exit(0);
}

console.log('🏦  BI-Rate refresh\n');

const prior = existsSync(CACHE) ? JSON.parse(readFileSync(CACHE, 'utf8')) : null;
const priorHistory = prior?.history ?? [];
console.log(`  cache: ${priorHistory.length} decision(s)${prior?.current != null ? `, current ${(prior.current * 100).toFixed(2)}% (eff. ${prior.effective})` : ' (empty)'}`);

console.log(`  ↳ scraping ${BI_RATE_URL} …`);
let scraped;
try {
  scraped = await fetchBIRateSeries();
} catch (err) {
  // A failed scrape is NOT a failure of this job — the cache is still valid and every
  // consumer keeps resolving from it. Failing the workflow here would just cry wolf.
  console.warn(`  ⚠️  scrape failed (${err.message}) — cache left untouched.`);
  finish(false, 'No change (scrape unavailable).');
}

console.log(`  ✅ ${scraped.history.length} decision(s), latest ${(scraped.current * 100).toFixed(2)}% eff. ${scraped.effective}`);
console.log(`     coverage: ${scraped.history[scraped.history.length - 1].effective} → ${scraped.history[0].effective}`);

// ── Union prior ∪ scraped, newest-first, scraped wins on a shared date ────────
const merged = new Map();
for (const row of priorHistory) merged.set(row.effective, row.rate);
for (const row of scraped.history) merged.set(row.effective, row.rate);

const history = [...merged.entries()]
  .map(([effective, rate]) => ({ effective, rate }))
  .sort((a, b) => (a.effective < b.effective ? 1 : a.effective > b.effective ? -1 : 0));

const next = {
  _comment: prior?._comment ?? 'Bank Indonesia policy-rate cache — generated by portfolio-app/data/refresh-bi-rate.js. Never hand-edit.',
  generated: new Date().toISOString(),
  source: BI_RATE_URL,
  current: history[0].rate,
  effective: history[0].effective,
  history,
};

// Compare everything EXCEPT `generated` — a timestamp bump is not a change.
const significant = ({ current, effective, history }) => JSON.stringify({ current, effective, history });
const changed = !prior || significant(prior) !== significant(next);

if (!changed) finish(false, `No change — BI-Rate still ${(next.current * 100).toFixed(2)}% (eff. ${next.effective}), ${history.length} decision(s) cached.`);

const added = history.length - priorHistory.length;
const rateMoved = !!prior && prior.current !== next.current;

if (rateMoved) console.log(`\n  📈 RATE MOVED  ${(prior.current * 100).toFixed(2)}% → ${(next.current * 100).toFixed(2)}%  (eff. ${next.effective})`);
if (added > 0) console.log(`  +${added} newly captured decision(s)`);

// The backtest scores every historical rebalance at the rate in effect on that date, so
// it goes stale on EITHER a new policy rate or newly captured history — the initial
// backfill silently re-dates years of steps without moving `current` at all.
if (rateMoved || added > 0) {
  console.log(`  ↳ backtest is stale (${rateMoved ? 'rate moved' : `+${added} decision(s)`}) — flagging for re-run.`);
  setOutput('backtest_stale', 'true');
}

writeFileSync(CACHE, JSON.stringify(next, null, 2) + '\n');
setOutput('current', String(next.current));
setOutput('effective', next.effective);
finish(true, `Wrote ${CACHE} — current ${(next.current * 100).toFixed(2)}%, ${history.length} decision(s).`);
